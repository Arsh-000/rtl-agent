def _f(v, d=3, signed=False):
    if v is None:
        return "n/a"
    return f"{v:+.{d}f}" if signed else f"{v:.{d}f}"


def _pct(new, old):
    p = pct_change(new, old)
    return "n/a" if p is None else f"{p:+.1f}%"


def summary_text(state: dict, cfg) -> list[str]:
    rounds = [record_from_dict(r) for r in state["rounds"]]
    if not rounds:
        return ["No rounds were completed."]
    base = rounds[0]
    best = next((r for r in rounds if r.number == state.get("best_round")), base)
    lines = []
    if base.metrics:
        b = base.metrics
        lines.append(f"Starting point (round 0): setup slack {_f(b['setup_ws'])} ns, hold slack {_f(b['hold_ws'])} ns, "
                     f"area {_f(b['area'], 1)} um2, power {_f(b['power_mw'], 4)} mW, {b['flop_bits']} flip-flop bits.")
    if best.metrics and best.number != base.number:
        m, b = best.metrics, base.metrics
        ds = None if m["setup_ws"] is None or b["setup_ws"] is None else m["setup_ws"] - b["setup_ws"]
        lines.append(f"Best version: round {best.number} - setup slack {_f(m['setup_ws'])} ns "
                     f"({_f(ds, 3, True)} ns), area {_f(m['area'], 1)} um2 ({_pct(m['area'], b['area'])}), "
                     f"power {_f(m['power_mw'], 4)} mW ({_pct(m['power_mw'], b['power_mw'])}), "
                     f"extra latency {m.get('latency', 0)} cycle(s).")
    elif best.number == base.number:
        lines.append("No proposal beat the starting design; the best version is still round 0.")
    proposals = [r for r in rounds if r.number != 0]
    counts = {s: len([r for r in proposals if r.status == s]) for s in ("kept", "rejected", "invalid", "duplicate")}
    lines.append(f"{len(proposals)} proposal(s): {counts['kept']} kept, {counts['rejected']} correct but not better, "
                 f"{counts['invalid']} failed checks, {counts['duplicate']} duplicate(s).")
    parent_metrics = {r.number: r.metrics for r in rounds}
    for r in proposals:
        if r.status == "kept" and r.metrics and parent_metrics.get(r.parent):
            p = parent_metrics[r.parent]
            ds = None if r.metrics["setup_ws"] is None or p["setup_ws"] is None else r.metrics["setup_ws"] - p["setup_ws"]
            lines.append(f"Round {r.number} ({r.phase}) kept: {r.idea} - slack {_f(ds, 3, True)} ns, "
                         f"area {_pct(r.metrics['area'], p['area'])}, power {_pct(r.metrics['power_mw'], p['power_mw'])}.")
    if best.metrics:
        st = targets_status(Metrics.from_dict(best.metrics), cfg.targets)
        met = [k for k, v in st.items() if v]
        unmet = [k for k, v in st.items() if not v]
        lines.append(f"Targets met: {', '.join(met) or 'none'}" + (f"; not met: {', '.join(unmet)}." if unmet else "."))
    lines.append(f"Stopped because: {state.get('stop_reason') or 'still running'}")
    return lines


def _chart_png(rounds) -> str:
    """Three small charts (slack, area, power per round) as an embedded PNG."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return ""
    measured = [r for r in rounds if r.metrics]
    if not measured:
        return ""
    colors = {"baseline": "#5b6770", "kept": "#1a7f37", "rejected": "#c4661f"}
    fig, axes = plt.subplots(1, 3, figsize=(11, 2.9))
    for ax, key, title in zip(axes, ("setup_ws", "area", "power_mw"),
                              ("Worst setup slack (ns)", "Area (um2)", "Power (mW)")):
        xs = [r.number for r in measured if r.metrics.get(key) is not None]
        ys = [r.metrics[key] for r in measured if r.metrics.get(key) is not None]
        ax.plot(xs, ys, color="#c9d3dd", linewidth=1, zorder=1)
        ax.scatter(xs, ys, c=[colors.get(r.status, "#888") for r in measured if r.metrics.get(key) is not None],
                   zorder=2, s=36)
        if key == "setup_ws":
            ax.axhline(0, color="#b42318", linewidth=0.8, linestyle="--")
        ax.set_title(title, fontsize=10)
        ax.set_xlabel("round", fontsize=8)
        ax.tick_params(labelsize=8)
        ax.set_xticks(xs)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    fig.text(0.01, 0.01, "grey = baseline, green = kept, orange = measured but not better "
             "(failed proposals have no measurements)", fontsize=7.5, color="#5b6770")
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110)
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode()


def _side_by_side(store: RunStore, r) -> str:
    if r.parent is None:
        return ""
    try:
        old = store.read_rtl(r.parent)
        new = store.read_rtl(r.number)
    except FileNotFoundError:
        return ""
    out = []
    differ = difflib.HtmlDiff(tabsize=4, wrapcolumn=70)
    for name in sorted(set(old) | set(new)):
        a, b = old.get(name, ""), new.get(name, "")
        if a == b:
            continue
        out.append(f"<h5>{html.escape(name)}</h5>" + differ.make_table(
            a.splitlines(), b.splitlines(), f"round {r.parent}", f"round {r.number}", context=True, numlines=3))
    return "\n".join(out)


def _header_comment(text: str, top: str) -> str:
    """The // comment block directly above 'module <top>' (how most people describe a module)."""
    lines = text.splitlines()
    idx = next((i for i, l in enumerate(lines) if re.match(rf"\s*module\s+{re.escape(top)}\b", l)), None)
    if idx is None:
        return ""
    block = []
    for l in reversed(lines[:idx]):
        s = l.strip()
        if s.startswith("//"):
            block.append(s[2:].strip())
        elif s == "" and not block:
            continue
        else:
            break
    return "\n".join(reversed(block)).strip()


def design_section(store: RunStore, state: dict, cfg) -> dict:
    """What the design is: description, interface, clock, size, and the original RTL."""
    files = store.read_rtl(0) if (store.round_dir(0) / "rtl").exists() else {}
    if cfg.design.description:
        desc, source = cfg.design.description.strip(), "from the config (design.description)"
    elif cfg.mode == "spec" and cfg.spec:
        desc, source = cfg.spec.text.strip(), "the specification given to the agent (spec mode)"
    else:
        desc = next((c for c in (_header_comment(t, cfg.design.top) for t in files.values()) if c), "")
        source = "the comment above the top module in the RTL" if desc else ""
    info = state.get("reference_info") or {}
    clocks = set(info.get("clocks", []))
    resets = {r["port"]: r for r in info.get("resets", [])}
    ports = []
    for p in info.get("ports", []):
        if p["name"] in clocks:
            role = "clock"
        elif p["name"] in resets:
            r = resets[p["name"]]
            role = f"reset ({'active-high' if r['active_high'] else 'active-low'}, {r['kind']})"
        else:
            role = "data / control input" if p["direction"] == "input" else "output"
        ports.append(dict(name=p["name"], dir=p["direction"], width=p["width"], role=role))
    period = state.get("clock_period_ns")
    facts = [("top module", cfg.design.top),
             ("clock period", f"{period} ns ({1000 / period:.0f} MHz)" if period else "n/a"),
             ("flip-flop bits", info.get("flop_bits", "n/a")), ("memory bits", info.get("memory_bits", 0)),
             ("files", ", ".join(f"{n} ({len(t.splitlines())} lines)" for n, t in files.items())),
             ("starting point", "written by the LLM from the specification" if cfg.mode == "spec"
              else "the user's RTL")]
    rtl = "\n\n".join(f"// ===== {n} =====\n{t.rstrip()}" for n, t in files.items())
    return dict(desc=desc, desc_source=source, ports=ports, facts=facts, rtl=rtl)


