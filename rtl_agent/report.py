def write_reports(store: RunStore, state: dict, cfg) -> None:
    rounds = [record_from_dict(r) for r in state["rounds"]]
    if not rounds:
        return
    by_no = {r.number: r for r in rounds}
    best_no = state.get("best_round")
    best = by_no.get(best_no)
    base = rounds[0]

    rows, details = [], []
    for r in rounds:
        m = r.metrics or {}
        pm = (by_no[r.parent].metrics if r.parent is not None and r.parent in by_no else None) or {}
        rows.append(dict(n=r.number, phase=r.phase, idea=r.idea, ws=_f(m.get("setup_ws")), hws=_f(m.get("hold_ws")),
                         area=_f(m.get("area"), 1), darea=_pct(m.get("area"), pm.get("area")) if m and pm else "",
                         power=_f(m.get("power_mw"), 4), flops=m.get("flop_bits", ""), lat=m.get("latency", ""),
                         verified=", ".join(r.checks.get("verified_by", [])) if r.checks else "",
                         status=r.status, reason=r.reason))
        checks_txt = []
        for name in ("testbench", "equivalence", "formal"):
            c = (r.checks or {}).get(name)
            if not c:
                continue
            if name == "testbench":
                checks_txt.append(f"testbench: {'PASSED' if c['passed'] else 'FAILED'}")
            elif name == "equivalence":
                if c["ran"]:
                    checks_txt.append(f"co-simulation vs original: {'PASSED' if c['passed'] else 'FAILED'}"
                                      f" (latency {c['latency']}, {c['compared_cycles']} cycles compared, "
                                      f"output bits toggled: {c['outputs_toggled']})")
                else:
                    checks_txt.append(f"co-simulation: not run - {c['detail']}")
                if c.get("detail") and not c["passed"]:
                    checks_txt.append(c["detail"])
            else:
                checks_txt.append(f"formal ({c['status']}): {c['detail']}")
        if r.status in ("invalid", "duplicate"):
            checks_txt.append(f"REJECTED: {r.reason}")
            fail = store.round_dir(r.number) / "work"
            checks_txt.append(f"(details in {fail})")
        paths = "\n".join(f"slack {_f(p.get('slack'))} ns, {p.get('cells', 0)} gates: {p['startpoint']} -> "
                          f"{p['endpoint']}  [{', '.join(p.get('rtl_lines', [])[:6])}]"
                          for p in (r.analysis or {}).get("paths", [])[:3])
        claims = [dict(k=k, claimed=v["claimed"] or "-", measured=v["measured"] or "-",
                       correct="-" if v["correct"] is None else ("yes" if v["correct"] else "NO"))
                  for k, v in (r.claims or {}).items()]
        details.append(dict(n=r.number, phase=r.phase, status=r.status, idea=r.idea, plan=r.plan, claims=claims,
                            checks="\n".join(checks_txt), paths=paths, parent=r.parent,
                            diff=_side_by_side(store, r), open=(r.status == "kept")))

    targets = []
    if best and best.metrics and base.metrics:
        bm, km = Metrics.from_dict(base.metrics), Metrics.from_dict(best.metrics)
        st = targets_status(km, cfg.targets)
        t = cfg.targets
        targets.append(dict(name="setup slack (ns)", req=f">= {t.min_setup_slack_ns}", base=_f(bm.setup_ws),
                            best=_f(km.setup_ws), ok=st["timing"]))
        targets.append(dict(name="hold slack (ns)",
                            req=f">= {t.min_hold_slack_ns}" if t.min_hold_slack_ns is not None
                            else "reported only (fixed in physical design)", base=_f(bm.hold_ws),
                            best=_f(km.hold_ws), ok=st["timing"] if t.min_hold_slack_ns is not None else None))
        targets.append(dict(name="area (um2)", req=f"<= {t.max_area_um2}" if t.max_area_um2 else "minimize",
                            base=_f(bm.area, 1), best=_f(km.area, 1), ok=st.get("area")))
        targets.append(dict(name="power (mW)", req=f"<= {t.max_power_mw}" if t.max_power_mw else "minimize",
                            base=_f(bm.power_mw, 4), best=_f(km.power_mw, 4), ok=st.get("power")))

    elapsed = state.get("elapsed_before_resume", 0.0)
    info = [("LLM provider", state.get("llm_provider", "?")), ("mode", cfg.mode),
            ("top module", cfg.design.top), ("SDC", state.get("sdc", "?")),
            ("cell library", str(cfg.library.liberty)), ("latency policy",
             f"{cfg.latency.policy} (max extra {cfg.latency.max_extra_cycles})" if cfg.latency.policy == "flexible"
             else "fixed"), ("priority", " > ".join(cfg.priority))]
    info += [(f"tool: {k}", v) for k, v in (state.get("tool_versions") or {}).items()]
    summary = summary_text(state, cfg)
    design = design_section(store, state, cfg)
    page = Environment(autoescape=True).from_string(_TEMPLATE).render(
        project=cfg.project_name, status=state.get("status"), n_rounds=len(rounds),
        llm_calls=state.get("llm_calls", 0), tokens=state.get("tokens", 0), minutes=f"{elapsed / 60:.1f}",
        scripted=str(state.get("llm_provider", "")).startswith("scripted"),
        sdc_generated=state.get("sdc_generated"), sdc=state.get("sdc"),
        spec_tb=(cfg.mode == "spec" and not cfg.testbench), summary=summary, targets=targets,
        best_no=best_no, chart=_chart_png(rounds), rows=rows, details=details,
        sdc_problems=state.get("sdc_problems", []), sdc_hash=state.get("sdc_hash", ""), info=info,
        design=design)
    (store.dir / "report.html").write_text(page)

    md = [f"# rtl-agent report: {cfg.project_name}", "", f"Status: **{state.get('status')}**", ""]
    if str(state.get("llm_provider", "")).startswith("scripted"):
        md += ["> Offline test run: the scripted provider replayed hand-written responses (not an LLM).", ""]
    md += ["## The design", ""] + ([design["desc"], ""] if design["desc"] else []) + \
          ["| port | direction | width | role |", "|---|---|---|---|"] + \
          [f"| {p['name']} | {p['dir']} | {p['width']} | {p['role']} |" for p in design["ports"]] + [""] + \
          [f"- {k}: {v}" for k, v in design["facts"]] + [""]
    md += ["## Summary", ""] + [f"- {l}" for l in summary] + ["", "## Rounds", "",
           "| # | phase | change | setup WS | area | power | latency | verdict |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['n']} | {r['phase']} | {r['idea']} | {r['ws']} | {r['area']} | {r['power']} | {r['lat']} | "
                  f"{r['status']}: {r['reason']} |")
    (store.dir / "report.md").write_text("\n".join(md) + "\n")
