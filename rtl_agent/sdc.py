"""Light-weight helpers around the SDC (timing constraints) file.

We deliberately do NOT parse SDC fully - OpenSTA does that. Here we only:
  * fingerprint the file so we can prove it was never changed,
  * read clock names/periods to tell the LLM about the design,
  * check that the ports the SDC mentions exist in the design,
  * generate a basic SDC when the user gives only a clock period.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

from .adapters.inspect import DesignInfo


def fingerprint(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_clocks(text: str) -> list[dict]:
    clocks = []
    for line in _logical_lines(text):
        if not line.startswith("create_clock"):
            continue
        name = re.search(r"-name\s+\{?([\w$.]+)\}?", line)
        period = re.search(r"-period\s+([0-9.]+)", line)
        port = re.search(r"get_ports\s+\{?\s*([\w$.]+(?:\[\d+\])?)", line)
        clocks.append({"name": name.group(1) if name else (port.group(1) if port else "?"),
                       "period": float(period.group(1)) if period else None,
                       "port": port.group(1) if port else None})
    return clocks


def _logical_lines(text: str) -> list[str]:
    text = re.sub(r"\\\n", " ", text)                    # join continued lines
    return [l.split("#")[0].strip() if not l.strip().startswith("#") else ""
            for l in text.splitlines() if l.strip() and not l.strip().startswith("#")]


def referenced_ports(text: str) -> set[str]:
    names = set()
    for group in re.findall(r"get_ports\s+(\{[^}]*\}|\[[^\]]*\]|\S+)", text):
        for tok in re.split(r"[\s{}\[\]]+", group):
            tok = tok.strip()
            if tok and not any(c in tok for c in "*?$"):
                names.add(re.sub(r"\[\d+\]$", "", tok))
    return names


def check_against_design(text: str, info: DesignInfo) -> list[str]:
    """Problems that would make timing results misleading."""
    problems = []
    ports = {p.name for p in info.ports}
    missing = sorted(referenced_ports(text) - ports)
    if missing:
        problems.append(f"SDC refers to ports that do not exist in the design: {', '.join(missing)}")
    clocks = read_clocks(text)
    clock_ports = {c["port"] for c in clocks if c["port"]}
    for clk in info.clocks:
        if clk not in clock_ports:
            problems.append(f"design clock '{clk}' has no create_clock in the SDC - its paths are unconstrained")
    if info.is_sequential and not clocks:
        problems.append("SDC defines no clocks, so no flip-flop path is timed")
    if "set_input_delay" not in text:
        problems.append("SDC has no set_input_delay: paths from inputs are timed against zero delay")
    if "set_output_delay" not in text:
        problems.append("SDC has no set_output_delay: paths to outputs are not constrained")
    return problems


def generate_basic_sdc(info: DesignInfo, period_ns: float, clock_port: str | None = None) -> str:
    """A simple starting SDC. Inputs arrive 10% into the cycle, outputs are due 10% before the end."""
    clk = clock_port or (info.clocks[0] if info.clocks else None)
    io = round(period_ns * 0.1, 4)
    lines = ["# Basic SDC generated by rtl-agent - REVIEW IT before trusting timing results.",
             f"# Clock period {period_ns} ns; I/O delays are 10% of the period."]
    if clk and info.port(clk):
        lines.append(f"create_clock -name {clk} -period {period_ns} [get_ports {clk}]")
        ref = clk
    else:
        lines.append(f"create_clock -name vclk -period {period_ns}   ;# virtual clock (combinational design)")
        ref = "vclk"
    data_in = [p.name for p in info.ports if p.direction == "input" and p.name != clk]
    if data_in:
        lines.append(f"set_input_delay {io} -clock {ref} [get_ports {{{' '.join(data_in)}}}]")
    lines.append(f"set_output_delay {io} -clock {ref} [all_outputs]")
    return "\n".join(lines) + "\n"
